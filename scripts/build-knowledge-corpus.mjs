#!/usr/bin/env node
// Bundles the public OKF app guides into the asha-knowledge edge function, so
// the function indexes only version-controlled text and never accepts
// documents from a request.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { okfDocuments } from "../okf/generated.js";

const corpus = okfDocuments
  .filter((c) => c.status !== "deprecated")
  .map(
    ({ id, module, title, description, text, provenance, verification }) => ({
      id,
      module,
      title,
      description,
      text,
      provenance,
      verification,
    }),
  );
const version = createHash("sha256")
  .update(JSON.stringify(corpus))
  .digest("hex")
  .slice(0, 16);
// Contextual retrieval: LLM-written chunk contexts, keyed by chunk id. They
// only apply to the corpus version they were written for.
const contextFile = JSON.parse(
  await readFile(
    new URL("../okf/retrieval/chunk-contexts.json", import.meta.url),
    "utf8",
  ),
);
const contexts =
  contextFile.corpusVersion === version ? contextFile.contexts : {};
if (contextFile.corpusVersion !== version)
  console.warn(
    `chunk contexts are for corpus ${contextFile.corpusVersion}, not ${version}: skipped`,
  );
const contextsVersion = createHash("sha256")
  .update(JSON.stringify(contexts))
  .digest("hex")
  .slice(0, 8);
const source = `// Generated by node scripts/build-knowledge-corpus.mjs from okf/*.md. Do not edit by hand.
export const CORPUS_VERSION = ${JSON.stringify(version)};
export const CORPUS = ${JSON.stringify(corpus, null, 2)} as const;
export const CONTEXTS_VERSION = ${JSON.stringify(contextsVersion)};
export const CHUNK_CONTEXTS: Record<string, string> = ${JSON.stringify(contexts, null, 2)};
`;
await writeFile(
  new URL("../supabase/functions/asha-knowledge/corpus.ts", import.meta.url),
  source,
);
console.log(
  `corpus ${version}: ${corpus.length} concepts, ${Object.keys(contexts).length} chunk contexts (${contextsVersion})`,
);
